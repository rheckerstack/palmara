import * as React from "react";
import { cn } from "@/lib/utils";

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & {
    glow?: string;
    accentColor?: string;
  }
>(({ className, glow, accentColor, style, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-[22px] border bg-gradient-to-br from-[rgba(255,255,255,0.045)] to-[rgba(255,255,255,0.01)] backdrop-blur-sm transition-all duration-250",
      className
    )}
    style={{
      borderColor: accentColor ? `${accentColor}28` : undefined,
      boxShadow: glow ? `0 8px 48px ${glow}` : undefined,
      ...style,
    }}
    {...props}
  />
));
Card.displayName = "Card";

